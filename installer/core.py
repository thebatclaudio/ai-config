"""
installer.core
==============

Tool-agnostic building blocks shared by every adapter:

    * logging helpers + per-run recap (``Report``)
    * ``.env`` loading and ``{{TOKEN}}`` template rendering
    * deep JSON merge (existing values win) and atomic JSON writes with backup
    * idempotent symlink management (Windows junction fallback) and uninstall
    * ``Context``: everything an adapter needs for one run

Moved out of the original ``setup.py`` with no behavioral change, except
that an unchanged JSON config is no longer re-written and backed up.
"""

from __future__ import annotations

import json
import os
import platform
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

ENV_FILENAME = ".env"
ENV_EXAMPLE_FILENAME = ".env.example"

# {{KEY}} tokens (KEY = uppercase letters/digits/underscore).
TOKEN_RE = re.compile(r"\{\{\s*([A-Z_][A-Z0-9_]*)\s*\}\}")

# Marker written into every file generated by an adapter, so re-runs and
# uninstall only ever touch files the installer owns.
GENERATED_MARKER = "generated by ai-config installer — edit the source in ai-config, not this file"


# ---------------------------------------------------------------------------
# Logging
# ---------------------------------------------------------------------------

def _log(prefix: str, msg: str) -> None:
    print(f"{prefix} {msg}")


def log_ok(msg: str) -> None:
    _log("[OK]   ", msg)


def log_skip(msg: str) -> None:
    _log("[SKIP] ", msg)


def log_warn(msg: str) -> None:
    _log("[WARN] ", msg)


def log_error(msg: str) -> None:
    _log("[ERROR]", msg)


def log_info(msg: str) -> None:
    _log("[INFO] ", msg)


def timestamp() -> str:
    return datetime.now().strftime("%Y%m%d-%H%M%S")


# ---------------------------------------------------------------------------
# Run report (one per adapter) + context
# ---------------------------------------------------------------------------

@dataclass
class Report:
    """Tally of what one adapter did, printed in the end-of-run recap."""

    target: str
    created: List[str] = field(default_factory=list)
    skipped: List[str] = field(default_factory=list)
    replaced: List[str] = field(default_factory=list)
    removed: List[str] = field(default_factory=list)
    backups: List[str] = field(default_factory=list)
    collisions: List[str] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)


@dataclass
class Context:
    """Everything an adapter needs for one run."""

    repo_root: Path
    env: Dict[str, str]
    dry_run: bool = False
    force: bool = False
    local: bool = False
    overrides: Dict[str, Optional[str]] = field(default_factory=dict)

    def setting(self, key: str) -> Optional[str]:
        """Look up a setting: CLI override > .env > process environment."""
        value = self.overrides.get(key)
        if value:
            return value
        value = self.env.get(key) or os.environ.get(key)
        return value or None


# ---------------------------------------------------------------------------
# .env handling
# ---------------------------------------------------------------------------

def parse_env_file(path: Path) -> Dict[str, str]:
    """
    Minimal stdlib .env parser.

    Handles ``KEY=value``, ``export KEY=value``, quoted values, comments and
    blank lines. Does NOT handle variable expansion or inline comments.
    """
    values: Dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").split("\n"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):].strip()
        if "=" not in line:
            continue
        key, _, raw = line.partition("=")
        key, raw = key.strip(), raw.strip()
        if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in ("'", '"'):
            raw = raw[1:-1]
        if key:
            values[key] = raw
    return values


def load_env(repo_root: Path, required: bool = True) -> Dict[str, str]:
    """
    Load ``.env`` from the repo root. Exits with code 1 when it is missing and
    ``required`` is true. Prefers python-dotenv's richer parsing when present.
    """
    env_path = repo_root / ENV_FILENAME
    example_path = repo_root / ENV_EXAMPLE_FILENAME

    if not env_path.exists():
        if not required:
            return {"BASE_PROJECT_PATH": str(repo_root)}
        log_error(f"`.env` not found at {env_path}")
        if example_path.exists():
            log_warn(f"Found `{ENV_EXAMPLE_FILENAME}` instead. Copy it and edit:")
            log_warn(f"    cp {example_path} {env_path}")
        else:
            log_warn(f"Neither `.env` nor `{ENV_EXAMPLE_FILENAME}` exists in {repo_root}.")
        sys.exit(1)

    values = parse_env_file(env_path)

    try:
        from dotenv import dotenv_values  # type: ignore

        for k, v in dotenv_values(env_path).items():
            if v is None:
                continue
            existing = values.get(k)
            if not existing or existing.startswith("$"):
                values[k] = v
    except ImportError:
        pass

    base = values.get("BASE_PROJECT_PATH", "").strip()
    if not base or base.startswith("/absolute/path/to"):
        log_warn(f"BASE_PROJECT_PATH not set in `.env`; defaulting to {repo_root}")
        values["BASE_PROJECT_PATH"] = str(repo_root)

    return values


# ---------------------------------------------------------------------------
# Templates
# ---------------------------------------------------------------------------

def render_tokens(raw: str, env: Dict[str, str], json_escape: bool = False) -> Tuple[str, List[str]]:
    """Substitute ``{{KEY}}`` tokens. Returns (rendered, missing_keys)."""
    missing: List[str] = []

    def _sub(match: "re.Match[str]") -> str:
        key = match.group(1)
        if key not in env:
            missing.append(key)
            return match.group(0)
        return json.dumps(env[key])[1:-1] if json_escape else env[key]

    return TOKEN_RE.sub(_sub, raw), sorted(set(missing))


def render_json_template(template_path: Path, env: Dict[str, str]) -> Dict[str, Any]:
    """Render a JSON template with ``{{KEY}}`` tokens and parse it."""
    if not template_path.exists():
        log_error(f"Template not found: {template_path}")
        sys.exit(1)

    rendered, missing = render_tokens(
        template_path.read_text(encoding="utf-8"), env, json_escape=True
    )
    if missing:
        log_warn("Unsubstituted tokens (left as-is): " + ", ".join(missing))
    try:
        return json.loads(rendered)
    except json.JSONDecodeError as exc:
        log_error(f"Rendered template is not valid JSON: {exc}")
        log_error("Rendered content was:\n" + rendered)
        sys.exit(1)


# ---------------------------------------------------------------------------
# JSON config: load, merge, write
# ---------------------------------------------------------------------------

def load_json(path: Path) -> Dict[str, Any]:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        log_warn(f"Existing {path.name} is not valid JSON ({exc}); treating as empty.")
        return {}


def merge_configs(
    existing: Dict[str, Any],
    generated: Dict[str, Any],
) -> Tuple[Dict[str, Any], List[str]]:
    """
    Deep-merge ``generated`` into ``existing``. EXISTING values win.

        dicts   -> recursive merge
        lists   -> ordered union (existing first), not a collision
        scalars -> existing kept; differing values logged as collisions
    """
    collisions: List[str] = []

    def _merge(cur_existing: Any, cur_generated: Any, path: str) -> Any:
        if isinstance(cur_existing, dict) and isinstance(cur_generated, dict):
            out: Dict[str, Any] = dict(cur_existing)
            for key, gen_val in cur_generated.items():
                sub_path = f"{path}.{key}" if path else key
                out[key] = _merge(out[key], gen_val, sub_path) if key in out else gen_val
            return out
        if isinstance(cur_existing, list) and isinstance(cur_generated, list):
            merged: List[Any] = list(cur_existing)
            for item in cur_generated:
                if item not in merged:
                    merged.append(item)
            return merged
        if cur_existing != cur_generated:
            collisions.append(
                f"{path}: kept existing={cur_existing!r}, discarded template={cur_generated!r}"
            )
        return cur_existing

    if not existing:
        return dict(generated), collisions
    return _merge(existing, generated, path=""), collisions


def write_json(target: Path, data: Dict[str, Any], ctx: Context, report: Report) -> None:
    """
    Atomically write ``data`` to ``target``. Backs up an existing file first.
    Skips entirely when the content is unchanged.
    """
    if target.exists() and load_json(target) == data:
        log_skip(f"Unchanged: {target}")
        report.skipped.append(str(target))
        return

    if ctx.dry_run:
        log_info(f"[dry-run] would write {target}")
        if target.exists():
            log_info(f"[dry-run] would back up {target} -> {target.name}.bak.<timestamp>")
        report.created.append(str(target))
        return

    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        backup = target.with_suffix(target.suffix + f".bak.{timestamp()}")
        shutil.copy2(target, backup)
        log_warn(f"Backed up existing config: {backup}")
        report.backups.append(str(backup))

    with tempfile.NamedTemporaryFile(
        "w", delete=False, dir=str(target.parent), prefix=f".{target.stem}.",
        suffix=".json.tmp", encoding="utf-8",
    ) as tmp:
        json.dump(data, tmp, indent=2, ensure_ascii=False)
        tmp.write("\n")
        tmp_name = tmp.name
    os.replace(tmp_name, target)
    log_ok(f"Wrote {target}")
    report.created.append(str(target))


