# Symlinks
# ---------------------------------------------------------------------------

def is_symlink_to(link: Path, expected: Path) -> bool:
    """True iff ``link`` is a symlink resolving to ``expected``."""
    try:
        return link.is_symlink() and link.resolve() == expected.resolve()
    except OSError:
        return False


def _windows_create_junction(src: Path, dst: Path) -> None:
    """NTFS directory junction (no admin / Developer Mode required)."""
    import _winapi  # type: ignore[import-not-found]

    if dst.exists() or dst.is_symlink():
        dst.unlink()
    _winapi.CreateJunction(str(src), str(dst))


def ensure_symlink(src: Path, dst: Path, ctx: Context, report: Report, relative: bool = False) -> None:
    """
    Make ``dst`` a symlink to ``src``. Idempotent.

    * correct link            -> skip
    * stale/broken symlink    -> replaced
    * real file or directory  -> refused unless ``ctx.force`` (then backed up)
    * ``relative=True``       -> link target written relative to ``dst.parent``
    """
    rel = f"{dst} -> {src}"

    if not src.exists():
        log_warn(f"Source missing, skipping: {src}")
        report.skipped.append(rel)
        return

    if is_symlink_to(dst, src):
        log_skip(f"Symlink already correct: {rel}")
        report.skipped.append(rel)
        return

    if dst.exists() or dst.is_symlink():
        if dst.is_symlink():
            if ctx.dry_run:
                log_info(f"[dry-run] would remove stale symlink: {dst}")
            else:
                dst.unlink()
                log_warn(f"Removed stale symlink: {dst}")
        else:
            if not ctx.force:
                log_warn(f"Refusing to replace existing real path: {dst} (use --force to back up and replace)")
                report.skipped.append(rel)
                return
            backup = dst.with_name(dst.name + f".bak.{timestamp()}")
            if ctx.dry_run:
                log_info(f"[dry-run] would back up {dst} -> {backup}")
            else:
                shutil.move(str(dst), str(backup))
                log_warn(f"Backed up real path: {dst} -> {backup}")
                report.backups.append(str(backup))
            report.replaced.append(rel)

    if ctx.dry_run:
        log_info(f"[dry-run] would create symlink: {rel}")
        report.created.append(rel)
        return

    dst.parent.mkdir(parents=True, exist_ok=True)
    target = Path(os.path.relpath(src, dst.parent)) if relative else src
    try:
        os.symlink(target, dst, target_is_directory=src.is_dir())
        log_ok(f"Created symlink: {rel}")
        report.created.append(rel)
        return
    except OSError as exc:
        winerror = getattr(exc, "winerror", None)
        if platform.system() == "Windows" and winerror == 1314 and src.is_dir():
            log_warn("Symlink creation denied (needs Developer Mode or admin). Falling back to a junction.")
            try:
                _windows_create_junction(src, dst)
                log_ok(f"Created junction: {rel}")
                report.created.append(rel)
                return
            except Exception as junction_exc:  # noqa: BLE001
                log_error(f"Junction fallback failed for {dst}: {junction_exc}")
                report.errors.append(f"{rel} ({junction_exc})")
                return
        log_error(f"Failed to create symlink {rel}: {exc}")
        if platform.system() == "Windows":
            log_warn("Hint: enable Developer Mode or run from an elevated shell.")
        else:
            log_warn(f"Hint: check write permissions on {dst.parent}.")
        report.errors.append(f"{rel} ({exc})")


def remove_symlink_into(dst: Path, root: Path, ctx: Context, report: Report) -> None:
    """Remove ``dst`` only if it is a symlink pointing inside ``root``."""
    if not dst.is_symlink():
        if dst.exists():
            log_skip(f"Not a symlink, leaving alone: {dst}")
        return
    try:
        target = dst.resolve()
    except OSError as exc:
        log_warn(f"Could not read symlink {dst}: {exc}")
        return
    root = root.resolve()
    if target != root and root not in target.parents:
        log_skip(f"Symlink does not point into this repo, leaving alone: {dst} -> {target}")
        return
    if ctx.dry_run:
        log_info(f"[dry-run] would remove symlink {dst} -> {target}")
    else:
        dst.unlink()
        log_ok(f"Removed symlink {dst}")
    report.removed.append(str(dst))


def ensure_dir(path: Path, ctx: Context, report: Report) -> None:
    if path.is_dir():
        return
    if ctx.dry_run:
        log_info(f"[dry-run] would create directory {path}")
    else:
        path.mkdir(parents=True, exist_ok=True)
        log_ok(f"Created directory {path}")
    report.created.append(str(path))


# ---------------------------------------------------------------------------
# Recap
# ---------------------------------------------------------------------------

def print_recap(reports: List[Report], dry_run: bool) -> None:
    print()
    print("=" * 72)
    print(" Setup recap" + (" (dry-run)" if dry_run else ""))
    print("=" * 72)
    for r in reports:
        print(f"\n## {r.target}")
        log_ok(f"Created/updated: {len(r.created)}")
        for e in r.created:
            print(f"         + {e}")
        log_skip(f"Unchanged/skipped: {len(r.skipped)}")
        for e in r.skipped:
            print(f"         - {e}")
        for label, items, mark in (
            ("Replaced real paths", r.replaced, "!"),
            ("Removed", r.removed, "x"),
            ("Backups created", r.backups, ">"),
        ):
            if items:
                log_warn(f"{label}: {len(items)}")
                for e in items:
                    print(f"         {mark} {e}")
        if r.collisions:
            log_warn(f"Config merge collisions ({len(r.collisions)}) — EXISTING values were kept:")
            for e in r.collisions:
                print(f"         * {e}")
        for n in r.notes:
            log_info(n)
        if r.errors:
            log_error(f"Errors: {len(r.errors)}")
            for e in r.errors:
                print(f"         x {e}")
    print("=" * 72)
